-- 확인
-- 1) 축별 7문항씩 42문항이어야 한다.
select a.id, a.name, count(i.code) as "문항"
  from readiness_areas a left join readiness_items i on i.area = a.id
 group by a.id, a.name, a.sort_order order by a.sort_order;
--
-- 2) 루브릭이 5개씩 다 있는가. 비면 "모르니까 3점" 을 못 줄인다.
select code, jsonb_array_length(rubric) as "루브릭"
  from readiness_items where jsonb_array_length(rubric) <> 5 order by code;
--
-- 3) 응답자 분포. 한 사람이 다 답할 수 없다는 것을 눈으로 확인한다.
select respondent, count(*) as "문항", string_agg(code, ', ' order by code) as "목록"
  from readiness_items group by respondent order by count(*) desc;
